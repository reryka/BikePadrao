CREATE TABLE categoria (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           nome VARCHAR(100) NOT NULL,
                           slug VARCHAR(120) NOT NULL,

                           ativo BOOLEAN NOT NULL DEFAULT TRUE,

                           data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT uk_categoria_nome UNIQUE (nome),
                           CONSTRAINT uk_categoria_slug UNIQUE (slug)
);


CREATE TABLE marca (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       nome VARCHAR(100) NOT NULL,
                       slug VARCHAR(120) NOT NULL,

                       ativo BOOLEAN NOT NULL DEFAULT TRUE,

                       data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT uk_marca_nome UNIQUE (nome),
                       CONSTRAINT uk_marca_slug UNIQUE (slug)
);


CREATE TABLE produto (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                         nome VARCHAR(200) NOT NULL,
                         slug VARCHAR(220) NOT NULL,
                         sku VARCHAR(50) NOT NULL,

                         descricao_curta VARCHAR(500),
                         descricao TEXT,

                         preco NUMERIC(12, 2) NOT NULL,
                         preco_promocional NUMERIC(12, 2),

                         estoque INTEGER NOT NULL DEFAULT 0,

                         ativo BOOLEAN NOT NULL DEFAULT TRUE,
                         destaque BOOLEAN NOT NULL DEFAULT FALSE,

                         categoria_id BIGINT NOT NULL,
                         marca_id BIGINT,

                         data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT uk_produto_slug UNIQUE (slug),
                         CONSTRAINT uk_produto_sku UNIQUE (sku),

                         CONSTRAINT ck_produto_preco
                             CHECK (preco >= 0),

                         CONSTRAINT ck_produto_preco_promocional
                             CHECK (
                                 preco_promocional IS NULL
                                     OR preco_promocional >= 0
                                 ),

                         CONSTRAINT ck_produto_estoque
                             CHECK (estoque >= 0),

                         CONSTRAINT fk_produto_categoria
                             FOREIGN KEY (categoria_id)
                                 REFERENCES categoria(id),

                         CONSTRAINT fk_produto_marca
                             FOREIGN KEY (marca_id)
                                 REFERENCES marca(id)
);


CREATE TABLE produto_imagem (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                produto_id BIGINT NOT NULL,

                                url VARCHAR(500) NOT NULL,

                                ordem INTEGER NOT NULL DEFAULT 0,
                                principal BOOLEAN NOT NULL DEFAULT FALSE,

                                data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT ck_produto_imagem_ordem
                                    CHECK (ordem >= 0),

                                CONSTRAINT fk_produto_imagem_produto
                                    FOREIGN KEY (produto_id)
                                        REFERENCES produto(id)
                                        ON DELETE CASCADE
);


CREATE INDEX idx_produto_categoria
    ON produto(categoria_id);


CREATE INDEX idx_produto_marca
    ON produto(marca_id);


CREATE INDEX idx_produto_ativo
    ON produto(ativo);


CREATE INDEX idx_produto_destaque
    ON produto(destaque);


CREATE INDEX idx_produto_imagem_produto
    ON produto_imagem(produto_id);